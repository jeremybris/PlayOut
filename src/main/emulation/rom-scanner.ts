export interface RomScanOptions {
  romsRoot: string
  findSystemForFolder: (folderName: string) => SystemDefinition | undefined
  log: Logger
  progress?: (found: number, message?: string) => void
  /** Maximum directory depth below a system folder (default 8). */
  maxDepth?: number
  /**
   * Lower-cased MAME BIOS and device set names (resources/systems/mame-assets.json, see loadMameAssets). Files with
   * such a stem are not games in arcade / Neo Geo folders, as in ES-DE (FileData::isArcadeAsset). Without the set
   * nothing is filtered.
   */
  arcadeAssets?: ReadonlySet<string>
}

export interface RomScanResult {
  games: ScannedGame[]
  /** ROM-root subfolders that matched no system. */
  unknownFolders: string[]
  /** Ids of the systems whose folders were scanned (including empty ones). */
  systemsScanned: string[]
}

/** Folders that hold art, manuals, BIOS files or saves rather than games (anywhere below the ROM root). */
const SKIPPED_FOLDERS = new Set([
  'media',
  'images',
  'manuals',
  'videos',
  'downloaded_media',
  'bios',
  'saves',
  'savestates',
  // Emulation\roms\PS3 HDD: where RPCS3's dev_hdd0 was before 0.1.120 (now Updates and DLC\PS3); not a system folder.
  'ps3 hdd'
])

/**
 * A folder the scan never looks into: SKIPPED_FOLDERS, and PlayOut's own set-aside and in-progress folders
 * (roms\PS3 HDD.playout-old after the PS3 HDD moved to Updates and DLC, a .playout-new copy).
 */
function isSkippedFolder(name: string): boolean {
  const lower = name.toLowerCase()
  return SKIPPED_FOLDERS.has(lower) || /\.playout-(new|old(-\d+)?)$/.test(lower)
}

/** Housekeeping files that are never games even when their extension matches. */
const IGNORED_FILES = new Set([
  'desktop.ini',
  'thumbs.db',
  'noload.txt',
  'flatten.txt',
  'systeminfo.txt',
  'systems.txt',
  'gamelist.xml'
])

/**
 * ES-DE hides MAME BIOS and device sets as "arcade assets" for systems on the arcade and neogeo platforms. PlayOut
 * maps ES-DE's `mame` system to its own platformKey, so it is listed here too.
 */
const ARCADE_PLATFORM_KEYS = new Set(['arcade', 'mame', 'neogeo'])

const mameAssetsSchema = z.object({
  _license: z.string().optional(),
  bioses: z.array(z.string().min(1)),
  devices: z.array(z.string().min(1))
})

/** Parse the JSON text of mame-assets.json into one lower-cased set of BIOS + device names. */
export function parseMameAssets(text: string, source = 'mame-assets.json'): Set<string> {
  let raw: unknown
  try {
    raw = JSON.parse(text.charCodeAt(0) === 0xfeff ? text.slice(1) : text)
  } catch (err) {
    throw new Error(`${source} is not valid JSON: ${(err as Error).message}`, { cause: err })
  }
  const parsed = mameAssetsSchema.safeParse(raw)
  if (!parsed.success) {
    const issues = parsed.error.issues
      .slice(0, 5)
      .map((i) => `${i.path.join('.') || '<root>'}: ${i.message}`)
      .join('; ')
    throw new Error(`${source} is malformed: ${issues}`)
  }
  const names = new Set<string>()
  for (const name of [...parsed.data.bioses, ...parsed.data.devices]) names.add(name.toLowerCase())
  if (!names.size) throw new Error(`${source} lists no MAME BIOS or device sets`)
  return names
}

/**
 * Read resources/systems/mame-assets.json once (synchronously, at service creation): the MAME BIOS and device set
 * names ES-DE ships in resources/MAME/mamebioses.xml and mamedevices.xml, generated by scripts/build-systems.mjs.
 */
export function loadMameAssets(file: string): Set<string> {
  let text: string
  try {
    text = readFileSync(file, 'utf8')
  } catch (err) {
    throw new Error(`Cannot read the MAME BIOS/device list at ${file}: ${(err as Error).message}`, {
      cause: err
    })
  }
  return parseMameAssets(text, file)
}

interface Candidate {
  path: string
  name: string
  isDirectory: boolean
  size: number
  /** Game folder whose name gives the title (a PS4 dump launched through the eboot.bin at `path`). */
  gameFolder?: string
  /** Emulator command that takes `path`, used unless the user picked another one for the game. */
  emulatorId?: string
  /**
   * A PS3 game folder's kind: a disc dump (it holds PS3_GAME: Convert makes an ISO of it) or a PSN / HDD game (USRDIR at
   * its top: Convert makes a package of it). Recorded as extra.ps3Kind.
   */
  ps3Kind?: 'disc' | 'psn'
  /** A folder whose name has no extension to strip (a PS3 game folder named without .ps3). */
  plainFolder?: boolean
}

/**
 * Systems whose games are dumped as a folder of files with one executable to launch, by platformKey. A PS4 dump
 * (`PS4\DRIVECLUB - [EU]\`) holds eboot.bin plus many other .bin files (in sce_module and elsewhere), and ES-DE's
 * ps4 system lists .bin as a game extension: the folder is the game, launched through its eboot.bin with shadPS4's
 * eboot.bin command, and nothing else inside it is a game. A PS5 dump (`PS5\Astro Bot - [US]\`) is the same: eboot.bin
 * beside sce_sys\ and sce_module\. No emulator runs PS5 games yet, so it has no emulatorId and Play says so
 * (launch-command.ts). An extracted Xbox or Xbox 360 game folder (what Convert makes of a disc image, a "Games on
 * Demand" folder) is one game through its default.xbe / default.xex: other .xbe / .xex files and the 360's
 * extensionless files in it ($SystemUpdate, nxeart) are not games. Those rules hold only below the system folder
 * (`nested`: a default.xex lying in xbox360 itself is listed as a file), and a folder holding only that file is still
 * a game (`alone`: homebrew is often just its default.xex). An Xbox folder starts in Cxbx-Reloaded: xemu boots only
 * disc images.
 */
const GAME_FOLDER_EXECUTABLES: Readonly<
  Record<string, { file: string; emulatorId?: string; nested?: boolean; alone?: boolean }>
> = {
  ps4: { file: 'eboot.bin', emulatorId: 'shadps4-eboot-bin-standalone' },
  ps5: { file: 'eboot.bin' },
  xbox: { file: 'default.xbe', emulatorId: 'cxbx-reloaded-standalone', nested: true, alone: true },
  xbox360: { file: 'default.xex', nested: true, alone: true }
}

/** The file that makes a folder one game of this platform to the ROM scan (eboot.bin, default.xex), if it has one. */
export function gameFolderExecutableFile(platformKey: string): string | undefined {
  return GAME_FOLDER_EXECUTABLES[platformKey]?.file
}

/**
 * What a PS3 game folder is, by its layout, as RPCS3 boots it: a disc (JB folder: PS3_GAME in it) or a PSN game
 * (USRDIR in it). `strict` (a folder whose name carries no .ps3 / .ps3dir) also wants the PSN game's PARAM.SFO to
 * say it is a game (category HG).
 */
export async function ps3FolderKind(
  dir: string,
  strict = false
): Promise<'disc' | 'psn' | undefined> {
  if ((await statSafe(join(dir, 'PS3_GAME')))?.isDirectory()) return 'disc'
  if (!(await statSafe(join(dir, 'USRDIR')))?.isDirectory()) return undefined
  if (!strict) return 'psn'
  // Only a game RPCS3 boots (category HG): an update, DLC or game-data folder from a dev_hdd0 has the same layout.
  return (await sfoFileString(join(dir, 'PARAM.SFO'), 'CATEGORY')) === 'HG' ? 'psn' : undefined
}

/** The dumped-game executable among a folder's entries (case-insensitive), when the platform has one. */
export function gameFolderExecutable(
  platformKey: string,
  entries: readonly { name: string; isFile(): boolean }[],
  nested = true
): { name: string; emulatorId?: string; alone?: boolean } | undefined {
  const rule = GAME_FOLDER_EXECUTABLES[platformKey]
  if (!rule || (rule.nested && !nested)) return undefined
  const hit = entries.find((e) => e.isFile() && e.name.toLowerCase() === rule.file)
  return hit
    ? { name: hit.name, emulatorId: rule.emulatorId, ...(rule.alone ? { alone: true } : {}) }
    : undefined
}

/** `name` is a dumped game's executable (eboot.bin), the file that makes its folder a game to the ROM scan. */
export function isGameFolderExecutableName(name: string): boolean {
  const lower = name.toLowerCase()
  return Object.values(GAME_FOLDER_EXECUTABLES).some((rule) => rule.file === lower)
}

/**
 * The folder that is the whole game when a ROM game is launched through a dumped-game executable (a PS4 dump's
 * eboot.bin): the folder holding `mainPath`, absolute. Null for every other ROM, and for an executable lying directly in
 * a system folder (`ps4\eboot.bin`: the system folder is never one game). The scanner records the folder as
 * extra.gameFolder; a record without it still counts when the file is its platform's executable.
 */
export function romGameFolder(
  mainPath: string,
  game: { externalId: string; platformId?: string; extra?: Record<string, unknown> }
): string | null {
  if (typeof game.externalId !== 'string') return null
  const segments = game.externalId.split(/[\\/]/).filter(Boolean)
  if (segments.length < 3) return null
  const name = basename(mainPath).toLowerCase()
  if (!isGameFolderExecutableName(name)) return null
  const folder = dirname(resolve(mainPath))
  const recorded = game.extra?.gameFolder
  if (typeof recorded === 'string' && recorded && pathKey(recorded) === pathKey(folder))
    return folder
  const rule = game.platformId ? GAME_FOLDER_EXECUTABLES[game.platformId] : undefined
  return rule?.file === name ? folder : null
}

/**
 * A dumped-game ROM (romGameFolder) whose stored measured size is not of its whole folder: one taken of its eboot.bin
 * alone before PlayOut measured the folder. Such a size is no size of the game; the install-size pass measures the
 * folder again (its measuredPath differs). False for every other game, and for the user's own or a store's size.
 */
export function staleGameFolderSize(game: {
  source: string
  externalId: string
  romPath?: string
  platformId?: string
  extra?: Record<string, unknown>
  installSize?: { how: string; path?: string }
}): boolean {
  const size = game.installSize
  if (game.source !== 'rom' || !size || size.how === 'store') return false
  if (typeof game.externalId !== 'string') return false
  const folder = romGameFolder(game.romPath ?? game.externalId, game)
  if (!folder) return false
  return !size.path || pathKey(size.path) !== pathKey(folder)
}

/** Extension of a file name from its last dot, lower-case; '.' when there is none (ES-DE's extensionless marker). */
export function extensionOf(name: string): string {
  const dot = name.lastIndexOf('.')
  return dot <= 0 ? '.' : name.slice(dot).toLowerCase()
}

/**
 * Names the scan never looks at, mirroring ES-DE's FileSystemUtil::isHidden ('.'-prefixed names) plus the
 * housekeeping files above. Underscore-prefixed names are ordinary entries, as in ES-DE (`_Unsorted\Game.sfc` is a
 * game and its gamelist entry must stay importable).
 */
export function isHiddenName(name: string): boolean {
  const lower = name.toLowerCase()
  // An unfinished conversion of PlayOut's Xbox helper (`Game.playout-partial.iso`, `Game.playout-partial`).
  // A disc image moved aside while its recompilation is tested (services/held-files.ts) is a dot name too.
  // A PS5 package being unpacked by the PS5 package helper (PS5PKGTool stages it in `Game.extracting.<32 hex>`).
  return (
    name.startsWith('.') ||
    isHeldDirName(name) ||
    IGNORED_FILES.has(lower) ||
    lower.includes('.playout-partial') ||
    /\.extracting\.[0-9a-f]{32}$/.test(lower)
  )
}

/** Files referenced by an .m3u playlist (one path per line, '#' comments), resolved against the playlist's folder. */
export function parseM3u(text: string, baseDir: string): string[] {
  return text
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#'))
    .map((line) => resolve(baseDir, line))
}

/** Data files referenced by a .cue sheet (`FILE "name" BINARY` lines), resolved against the sheet's folder. */
export function parseCueFiles(text: string, baseDir: string): string[] {
  const files: string[] = []
  for (const match of text.matchAll(/^\s*FILE\s+(?:"([^"]+)"|(\S+))/gim))
    files.push(resolve(baseDir, match[1] ?? match[2]))
  return files
}

function pathKey(p: string): string {
  return resolve(p).replace(/\//g, '\\').toLowerCase()
}

function stemOf(name: string): string {
  const dot = name.lastIndexOf('.')
  return dot <= 0 ? name : name.slice(0, dot)
}

/** Build the ScannedGame for one ROM file or game directory. */
export function romToScannedGame(
  system: SystemDefinition,
  romsRoot: string,
  candidate: Candidate
): ScannedGame {
  const externalId = relative(romsRoot, candidate.path).replace(/\\/g, '/')
  // A folder name has no extension to strip ("DRIVECLUB - [EU] [EN] [1.28]" would lose ".28]").
  const { title, tags } = candidate.gameFolder
    ? cleanRomTitle(basename(candidate.gameFolder), false)
    : cleanRomTitle(candidate.name, !candidate.plainFolder)
  const extra: Record<string, string | number | boolean> = {
    tags: tags.join(', '),
    extension: candidate.plainFolder ? '' : extensionOf(candidate.name),
    fileSize: candidate.size
  }
  if (candidate.isDirectory) extra.directory = true
  if (candidate.gameFolder) extra.gameFolder = candidate.gameFolder
  if (candidate.ps3Kind) extra.ps3Kind = candidate.ps3Kind
  const launch: ScannedGame['launch'] = {
    kind: 'emulator',
    systemId: system.id,
    romPath: candidate.path,
    ...(candidate.emulatorId ? { emulatorId: candidate.emulatorId } : {})
  }
  return {
    source: 'rom',
    externalId,
    platformId: system.id,
    title,
    romPath: candidate.path,
    launch,
    tracking: { mode: 'spawned' },
    extra
  }
}

/**
 * Walk `romsRoot/<system folder>/**` for every subfolder that matches a system and return one ScannedGame per ROM.
 * A directory whose name ends with one of the system's extensions (other than the extensionless '.' marker) or one
 * of its dirExtensions is a game itself and is not descended into, as ES-DE's populateFolder does (ROM-hack
 * folders like `snes\Hacks\Game.zip\`, `wiiu\Game.wua\`, `psx\Game.m3u\`). .m3u playlists hide the discs they
 * reference, .cue sheets hide their data tracks, folders holding a noload.txt are skipped, and in arcade folders
 * MAME BIOS/device sets (options.arcadeAssets) are not games, as in ES-DE. A dumped PS4 or PS5 game folder (one holding
 * eboot.bin, see GAME_FOLDER_EXECUTABLES) is one game titled from the folder and launched through its eboot.bin.
 */
export async function scanRomRoot(options: RomScanOptions): Promise<RomScanResult> {
  const { log } = options
  const romsRoot = resolve(options.romsRoot)
  const maxDepth = options.maxDepth ?? 8
  const games: ScannedGame[] = []
  const unknownFolders: string[] = []
  const systemsScanned: string[] = []
  const report = (message?: string): void => options.progress?.(games.length, message)

  const rootStat = await statSafe(romsRoot)
  if (!rootStat?.isDirectory()) {
    log.warn(`ROM folder does not exist or is not a directory: ${romsRoot}`)
    return { games, unknownFolders, systemsScanned }
  }

  const visible = (dir: string, entries: Awaited<ReturnType<typeof listDir>>): typeof entries =>
    entries
      .filter((e) => {
        if (!isHiddenName(e.name)) return true
        log.debug(`skipping ${join(dir, e.name)}: hidden or housekeeping name`)
        return false
      })
      .sort((a, b) => a.name.localeCompare(b.name, 'en'))

  const topLevel = visible(romsRoot, await listDir(romsRoot))

  for (const entry of topLevel) {
    const folder = join(romsRoot, entry.name)
    if (!(await isDirectoryEntry(entry.isDirectory(), entry.isSymbolicLink(), folder))) continue
    if (isSkippedFolder(entry.name)) continue
    const system = options.findSystemForFolder(entry.name)
    if (!system) {
      unknownFolders.push(entry.name)
      continue
    }
    if (await isFile(join(folder, 'noload.txt'))) {
      log.info(`skipping ${entry.name}: noload.txt present`)
      continue
    }
    systemsScanned.push(system.id)
    report(`Scanning ${system.name}…`)

    const extensions = new Set(system.extensions.map((e) => e.toLowerCase()))
    const dirExtensions = (system.dirExtensions ?? []).map((e) => e.toLowerCase())
    const candidates: Candidate[] = []
    const excluded = new Set<string>()
    const visited = new Set<string>()
    const platformKey = system.platformKey
    const arcadeAssets = ARCADE_PLATFORM_KEYS.has(system.platformKey)
      ? options.arcadeAssets
      : undefined

    async function walk(dir: string, depth: number): Promise<void> {
      let real: string
      try {
        real = await fs.realpath(dir)
      } catch {
        real = dir
      }
      const realKey = pathKey(real)
      if (visited.has(realKey)) {
        log.warn(`skipping ${dir}: directory loop`)
        return
      }
      visited.add(realKey)

      const entries = visible(dir, await listDir(dir))
      // A dumped game folder (PS4: it holds eboot.bin) is one game launched through that file; nothing in it is listed.
      const executable = gameFolderExecutable(platformKey, entries, depth > 0)
      // A folder holding nothing but the executable is not a game (shadPS4 needs the rest of the dump): what an older
      // PlayOut left when a host's PS4 game was downloaded as its eboot.bin alone. Left out, the host's game shows
      // its Download again, and that download completes the folder. A warning: the folder is in the library folder
      // and its game is not listed, which the log has to explain.
      if (executable && !executable.alone && entries.length === 1) {
        log.warn(`not listing ${dir}: it holds only ${executable.name}, not a whole game`)
        return
      }
      // A folder a download is still filling (a .part beside its executable) is not a game yet either; the download
      // puts the executable in place last, so this only guards against a part left over (a warning for the same reason).
      const part = executable
        ? entries.find((e) => e.isFile() && e.name.toLowerCase().endsWith('.part'))
        : undefined
      if (part) {
        log.warn(
          `not listing ${dir}: a download into it is not finished (${part.name} is still there)`
        )
        return
      }
      if (executable) {
        const full = join(dir, executable.name)
        const stat = await statSafe(full)
        if (stat?.isFile()) {
          candidates.push({
            path: full,
            name: executable.name,
            isDirectory: false,
            size: stat.size,
            gameFolder: dir,
            ...(executable.emulatorId ? { emulatorId: executable.emulatorId } : {})
          })
          return
        }
      }
      for (const e of entries) {
        const full = join(dir, e.name)
        const isDir = await isDirectoryEntry(e.isDirectory(), e.isSymbolicLink(), full)
        if (isDir) {
          const lower = e.name.toLowerCase()
          // ES-DE: a directory named like a game file IS the game ('.' marks extensionless files, never folders).
          const dirExt = extensionOf(e.name)
          if (
            (dirExt !== '.' && extensions.has(dirExt)) ||
            dirExtensions.some((ext) => lower.endsWith(ext))
          ) {
            const ps3Kind = platformKey === 'ps3' ? await ps3FolderKind(full) : undefined
            candidates.push({
              path: full,
              name: e.name,
              isDirectory: true,
              size: 0,
              ...(ps3Kind ? { ps3Kind } : {})
            })
            continue
          }
          // A PS3 game folder named without .ps3 (a JB folder as dumped, what Convert unpacks a disc image into) is a
          // game too: RPCS3 boots it the same way.
          const ps3Kind = platformKey === 'ps3' ? await ps3FolderKind(full, true) : undefined
          if (ps3Kind) {
            candidates.push({
              path: full,
              name: e.name,
              isDirectory: true,
              size: 0,
              ps3Kind,
              plainFolder: true
            })
            continue
          }
          if (isSkippedFolder(lower)) continue
          if (depth >= maxDepth) {
            log.warn(`not descending into ${full}: deeper than ${maxDepth} levels`)
            continue
          }
          if (await isFile(join(full, 'noload.txt'))) continue
          await walk(full, depth + 1)
          continue
        }
        const ext = extensionOf(e.name)
        if (!extensions.has(ext)) continue
        const stat = await statSafe(full)
        if (!stat?.isFile()) continue
        if (arcadeAssets?.has(stemOf(e.name).toLowerCase())) {
          log.debug(`skipping MAME BIOS/device set ${e.name}`)
          continue
        }
        if (ext === '.m3u' || ext === '.cue') {
          const text = await readTextIfExists(full)
          if (text !== null) {
            const referenced = ext === '.m3u' ? parseM3u(text, dir) : parseCueFiles(text, dir)
            for (const ref of referenced) excluded.add(pathKey(ref))
          }
        }
        candidates.push({ path: full, name: e.name, isDirectory: false, size: stat.size })
      }
    }

    await walk(folder, 0)

    let count = 0
    for (const candidate of candidates) {
      if (excluded.has(pathKey(candidate.path))) continue
      games.push(romToScannedGame(system, romsRoot, candidate))
      count++
    }
    log.info(
      `${system.id}: ${count} games (${candidates.length - count} playlist/cue members hidden)`
    )
    report(`${system.name}: ${count} games`)
  }

  const seen = new Set<string>()
  const unique = games.filter((g) => {
    const key = g.externalId.toLowerCase()
    if (seen.has(key)) return false
    seen.add(key)
    return true
  })
  if (unknownFolders.length) log.info(`folders matching no system: ${unknownFolders.join(', ')}`)
  return { games: unique, unknownFolders, systemsScanned }
}

async function isDirectoryEntry(
  isDirectory: boolean,
  isSymbolicLink: boolean,
  fullPath: string
): Promise<boolean> {
  if (isDirectory) return true
  if (!isSymbolicLink) return false
  const stat = await statSafe(fullPath)
  return !!stat && stat.isDirectory()
}

/** Name of the ROM-root subfolder a ROM lives in (first path segment of its relative path). */
export function systemFolderOf(romsRoot: string, romPath: string): string {
  const rel = relative(romsRoot, romPath).replace(/\\/g, '/')
  return rel.split('/')[0] ?? basename(dirname(romPath))
}

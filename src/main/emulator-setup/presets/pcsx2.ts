/** How long `pcsx2-qt -testconfig` may take (it loads Qt but shows no window). */
const TESTCONFIG_TIMEOUT_MS = 60_000

async function exists(path: string): Promise<boolean> {
  try {
    await fs.access(path)
    return true
  } catch {
    return false
  }
}

const hasVersion = (ui: string[] | null): boolean => entryValue(ui, 'SettingsVersion') === '1'
const isTrue = (v: string | undefined): boolean => v !== undefined && /^(true|1)$/i.test(v)

/**
 * Lets PCSX2 write its complete default PCSX2.ini. portable.txt must exist first (the configurator writes it; it is
 * touched again here so the file cannot land in Documents\PCSX2). Throws when PCSX2 did not produce a valid file: a
 * partial PCSX2.ini is never written in its place.
 */
async function generateDefaults(ctx: PresetContext, ini: string): Promise<void> {
  const E = ctx.emuDir
  await fs.writeFile(join(E, 'portable.txt'), '', { flag: 'a' })
  const r = await ctx.run(join(E, 'pcsx2-qt.exe'), ['-testconfig'], {
    cwd: E,
    timeoutMs: TESTCONFIG_TIMEOUT_MS
  })
  const valid = (await exists(ini)) && hasVersion(await readIniSection(ini, 'UI'))
  if (r.code !== 0 || !valid) {
    const detail = r.stderr.trim() || r.stdout.trim()
    throw new Error(
      `PCSX2 could not write its default settings: pcsx2-qt -testconfig ${
        r.code === null ? 'did not finish' : `exited with ${r.code}`
      }${valid ? '' : ' and inis\\PCSX2.ini is missing or has no [UI] SettingsVersion = 1'}${
        detail ? ` (${detail.slice(0, 500)})` : ''
      }`
    )
  }
}


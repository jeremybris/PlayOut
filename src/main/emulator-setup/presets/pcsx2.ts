/** Whether an ini value is (still) `def`: same text, or the same number ("1" and "1.000000"), any case. */
function isDefault(current: string | undefined, def: string): boolean {
  if (current === undefined) return true
  if (current.toLowerCase() === def.toLowerCase()) return true
  const [a, b] = [Number(current), Number(def)]
  return current.trim() !== '' && !Number.isNaN(a) && !Number.isNaN(b) && a === b
}

/** Writes PCSX2_SETTINGS over PCSX2's defaults; returns the labels of what changed. */
async function applyUserDefaults(ini: string): Promise<string[]> {
  const changed: string[] = []
  const sections = [...new Set(PCSX2_SETTINGS.map((s) => s.section))]
  for (const section of sections) {
    const lines = await readIniSection(ini, section)
    const values: Record<string, string> = {}
    for (const s of PCSX2_SETTINGS.filter((x) => x.section === section)) {
      const current = entryValue(lines, s.key)
      if (current === s.value || !isDefault(current, s.default)) continue
      values[s.key] = s.value
      changed.push(s.label)
    }
    if (Object.keys(values).length > 0) await setIniValues(ini, section, values)
  }
  return changed
}

export const applyPresets: ApplyPresets = async (ctx) => {
  const ini = join(ctx.emuDir, 'inis', 'PCSX2.ini')
  const created = !(await exists(ini))
  if (created) await generateDefaults(ctx, ini)

  const ui = await readIniSection(ini, 'UI')
  if (!hasVersion(ui)) {
    // PCSX2 will ask to reset this file to defaults when it starts; editing it now would be thrown away.
    ctx.log.warn('PCSX2: PCSX2.ini has no [UI] SettingsVersion = 1; leaving it for PCSX2 to reset')
    return
  }
  const values: Record<string, string> = {}
  if (ctx.firstTime) values.StartFullscreen = 'true'
  // Needed for the fullscreen launch: PCSX2 runs the setup wizard before booting the game, even with -batch. Cleared
  // when PlayOut generated the file, or on first-time setup when the wizard was never finished.
  if ((created || ctx.firstTime) && isTrue(entryValue(ui, 'SetupWizardIncomplete'))) {
    values.SetupWizardIncomplete = 'false'
  }
  // Big Picture when PCSX2 is opened by itself (a game PlayOut starts boots straight over it), once.
  if (newSince(ctx, BIG_PICTURE_VERSION) && !isTrue(entryValue(ui, 'StartBigPictureMode'))) {
    values.StartBigPictureMode = 'true'
  }
  if (Object.keys(values).length > 0) await setIniValues(ini, 'UI', values)

  // The user's emulation, video, audio and achievement choices, once, over PCSX2's own defaults only.
  if (newSince(ctx, PCSX2_SETTINGS_VERSION)) {
    const changed = await applyUserDefaults(ini)
    if (changed.length > 0) ctx.log.info(`PCSX2: set ${changed.join(', ')}`)
  }

  const sources = await readIniSection(ini, 'InputSources')
  if (isFalse(entryValue(sources, 'SDL'))) {
    ctx.log.info('PCSX2: the SDL input source is turned off; leaving the controllers as they are')
    return
  }
  // Start + Select opens the Big Picture pause menu in game, next to Escape on the keyboard.
  if (
    newSince(ctx, BIG_PICTURE_VERSION) &&
    (await addPadHotkey(ini, 'OpenPauseMenu', SDL_MENU_CHORD))
  ) {
    ctx.log.info('PCSX2: Start + Select opens the pause menu')
  }
  const pad1 = await readIniSection(ini, 'Pad1')
  if (!isUntouchedPad(pad1, PAD1)) {
    ctx.log.info('PCSX2: [Pad1] was changed by the user; leaving the controllers as they are')
    return
  }
  await replaceIniSection(
    ini,
    'Pad1',
    addBindings(pad1 ?? [`Type = ${TYPE}`, ...bindingLines(KEYBOARD_PAD1)], SDL_PAD)
  )
  const pad2 = await readIniSection(ini, 'Pad2')
  if (isUnusedPad(pad2, BINDING_KEYS)) {
    await replaceIniSection(
      ini,
      'Pad2',
      addBindings(setType(pad2 ?? [], TYPE), forDevice(SDL_PAD, 1))
    )
    ctx.log.info('PCSX2: bound SDL game controllers 0 and 1 to ports 1 and 2')
  } else {
    ctx.log.info('PCSX2: bound SDL game controller 0 to port 1 ([Pad2] is in use)')
  }
}

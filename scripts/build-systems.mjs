/** Build the SystemDefinition[] payload from the ES-DE systems extract (+ optional sorting data). */
export function buildSystems(esdeSystems, sorting = null) {
  const entries = Array.isArray(esdeSystems) ? esdeSystems : Object.values(esdeSystems)
  const systems = []
  for (const entry of entries) {
    const id = String(entry.name ?? '').trim()
    if (!id) throw new Error('ES-DE system without a name in the extract')
    const extensions = uniqueInOrder(entry.extensions.map(normalizeExtension).filter(Boolean))
    if (!extensions.length) throw new Error(`System ${id} has no extensions`)

    const commandIds = new Set()
    const removed = COMMAND_REMOVALS[id] ?? []
    const commands = (entry.commands ?? []).filter(
      (cmd) => !removed.includes(String(cmd.label ?? '').trim())
    )
    let emulators = commands.map((cmd) => {
      const label = cmd.label ? String(cmd.label).trim() : ''
      let base = label ? slug(label) || 'default' : 'default'
      let candidate = base
      for (let n = 2; commandIds.has(candidate); n++) candidate = `${base}-${n}`
      commandIds.add(candidate)
      const command = String(cmd.command).trim()
      return {
        id: candidate,
        label: label || 'Default',
        command: COMMAND_CHANGES[command] ?? command
      }
    })
    const merge = COMMAND_MERGES[id]
    if (merge) emulators = mergeCommands(id, emulators, merge)
    const preferred = COMMAND_DEFAULTS[id]
    if (preferred) {
      const found = emulators.find((e) => e.id === preferred)
      if (!found) throw new Error(`${id}: default command ${preferred} not found`)
      let hit = found
      if (NO_ARCHIVES.has(preferred) && extensions.some((e) => ARCHIVE_EXTENSIONS.includes(e))) {
        if (!emulators.some((e) => e !== found && e.command.includes('%EMULATOR_RETROARCH%')))
          throw new Error(`${id}: no RetroArch command for archived ROMs`)
        hit = { ...found, noArchives: true }
      }
      emulators = [hit, ...emulators.filter((e) => e !== found)]
    }
    if (!emulators.length) throw new Error(`System ${id} has no launch command`)

    const esdePlatform = String(entry.platform ?? '')
      .split(/[\s,]+/)
      .filter(Boolean)[0]
    const platformKey = id === 'mame' ? 'mame' : (PLATFORM_KEYS[esdePlatform] ?? esdePlatform ?? id)

    const known = KNOWN_SYSTEMS[id]
    const [fallbackManufacturer, fallbackYear] = manufacturerFromSorting(sorting, id)
    const manufacturer = known?.[0] ?? fallbackManufacturer
    const releaseYear = known?.[1] ?? fallbackYear

    const dirExtensions = uniqueInOrder([
      ...(DIR_EXTENSIONS[id] ?? []).filter((ext) => extensions.includes(ext)),
      ...(extensions.includes('.m3u') ? ['.m3u'] : [])
    ])
    const aliases = ALIASES[id] ?? []

    const system = { id, name: String(entry.fullname ?? id).trim() }
    if (aliases.length) system.aliases = aliases
    system.extensions = extensions
    system.platformKey = platformKey
    if (manufacturer) system.manufacturer = manufacturer
    if (releaseYear) system.releaseYear = releaseYear
    system.emulators = emulators
    if (dirExtensions.length) system.dirExtensions = dirExtensions
    systems.push(system)
  }

  validateSystems(systems)
  return { _license: LICENSE, systems }
}

/** Replace the commands `merge.replaces` names (by label) with one command at the first one's place. */
function mergeCommands(systemId, emulators, merge) {
  const replaced = merge.replaces.map((label) => {
    const hit = emulators.find((e) => e.label === label)
    if (!hit) throw new Error(`${systemId}: command '${label}' to merge not found`)
    return hit
  })
  if (emulators.some((e) => e.id === merge.id && !replaced.includes(e))) {
    throw new Error(`${systemId}: merged command id ${merge.id} is taken`)
  }
  const at = emulators.indexOf(replaced[0])
  const merged = {
    id: merge.id,
    label: merge.label,
    command: merge.command,
    aliases: uniqueInOrder([...replaced.map((e) => e.id), ...replaced.map((e) => e.label)])
  }
  const out = emulators.filter((e) => !replaced.includes(e))
  out.splice(at, 0, merged)
  return out
}

function validateSystems(systems) {
  const seen = new Map()
  const claim = (name, owner, kind) => {
    const key = name.toLowerCase()
    const existing = seen.get(key)
    if (existing) throw new Error(`${kind} '${name}' of ${owner} collides with ${existing}`)
    seen.set(key, `${kind} of ${owner}`)
  }
  for (const s of systems) claim(s.id, s.id, 'id')
  for (const s of systems) for (const alias of s.aliases ?? []) claim(alias, s.id, 'alias')
  for (const s of systems) {
    const ids = new Set()
    for (const e of s.emulators) {
      if (ids.has(e.id)) throw new Error(`Duplicate command id ${e.id} in ${s.id}`)
      ids.add(e.id)
    }
    for (const e of s.emulators)
      for (const alias of e.aliases ?? [])
        if (ids.has(alias) && alias !== e.id)
          throw new Error(`Command alias ${alias} of ${e.id} in ${s.id} is another command's id`)
  }
}

/** Rewrite an ES-DE find-rule entry so that it uses PlayOut's variables. Returns null to drop the entry. */
export function rewriteEntry(entry) {
  let out = String(entry)
  if (/^%ESPATH%\\\.\.\\Emulators\\/i.test(out))
    out = out.replace(/^%ESPATH%\\\.\.\\Emulators\\/i, '%ESPATH%\\Emulators\\')
  out = out.replace(/^~\\AppData\\Roaming\\/i, '%APPDATA%\\')
  out = out.replace(/^~\\AppData\\Local\\/i, '%LOCALAPPDATA%\\')
  out = out.replace(/^~\\/, '%USERPROFILE%\\')
  out = out.replace(/^C:\\Program Files \(x86\)\\/i, '%PROGRAMFILES(X86)%\\')
  out = out.replace(/^C:\\Program Files\\/i, '%PROGRAMFILES%\\')
  return out
}

/** Build the find-rules payload: ES-DE installer + portable rules merged, with PlayOut variable names. */
export function buildFindRules(esdeFindRules) {
  const merged = new Map()
  const lists = [...(esdeFindRules.findRules ?? []), ...(esdeFindRules.findRulesPortable ?? [])]
  for (const rule of lists) {
    const key = `${rule.kind}:${rule.name}`
    let target = merged.get(key)
    if (!target) {
      target = {
        kind: rule.kind,
        name: rule.name,
        notes: [...(rule.notes ?? [])],
        rules: new Map()
      }
      merged.set(key, target)
    }
    for (const r of rule.rules ?? []) {
      const list = target.rules.get(r.type) ?? []
      for (const entry of r.entries ?? []) {
        const rewritten =
          r.type === 'staticpath' || r.type === 'corepath' ? rewriteEntry(entry) : String(entry)
        if (rewritten && !list.includes(rewritten)) list.push(rewritten)
      }
      target.rules.set(r.type, list)
    }
  }

  const emulators = []
  const cores = []
  const missingNames = []
  for (const target of merged.values()) {
    const rules = [...target.rules.entries()].map(([type, entries]) => ({ type, entries }))
    if (target.kind === 'core') {
      cores.push({ id: target.name, rules })
      continue
    }
    const name = EMULATOR_NAMES[target.name]
    if (!name) missingNames.push(target.name)
    const item = { id: target.name, name: name ?? target.name }
    const description = target.notes.find(
      (n) =>
        !/^(Check for|This requires|Some reasonable|Steam release|Portable installation)/i.test(n)
    )
    if (description) item.description = description
    item.rules = rules
    if (DOWNLOAD_URLS[target.name]) item.downloadUrl = DOWNLOAD_URLS[target.name]
    emulators.push(item)
  }
  if (missingNames.length)
    console.warn(`No display name for emulator(s): ${missingNames.join(', ')} (using the id)`)
  for (const id of Object.keys(EMULATOR_NAMES)) {
    if (!merged.has(`emulator:${id}`))
      console.warn(`EMULATOR_NAMES has '${id}' but the extract has no such rule`)
  }
  return { _license: LICENSE, variables: VARIABLES, emulators, cores }
}


export function slug(text) {
  return String(text)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

function normalizeExtension(ext) {
  const trimmed = String(ext).trim().toLowerCase()
  if (!trimmed) return null
  if (trimmed === '.') return '.'
  return trimmed.startsWith('.') ? trimmed : `.${trimmed}`
}

function uniqueInOrder(values) {
  const seen = new Set()
  const out = []
  for (const v of values) {
    if (seen.has(v)) continue
    seen.add(v)
    out.push(v)
  }
  return out
}

async function readJsonFile(file) {
  return JSON.parse(await readFile(file, 'utf8'))
}

function manufacturerFromSorting(sorting, id) {
  const entry = sorting?.[id]
  if (!entry) return [undefined, undefined]
  const match = String(entry.manufacturer_year ?? '').match(/^(.*?)\s+-\s+(\d{4})$/)
  if (!match) return [undefined, undefined]
  const manufacturer = match[1] === 'Various' ? undefined : match[1]
  const year = match[2] === '0000' ? undefined : Number(match[2])
  return [manufacturer, year]
}


/** The ES-DE extract with PLAYOUT_SYSTEMS inserted (each after its `after` system, else at the end). */
export function withPlayOutSystems(esdeSystems, extra = PLAYOUT_SYSTEMS) {
  const entries = [...(Array.isArray(esdeSystems) ? esdeSystems : Object.values(esdeSystems))]
  for (const { after, ...entry } of extra) {
    if (entries.some((e) => e.name === entry.name)) throw new Error(`ES-DE now has ${entry.name}`)
    const at = entries.findIndex((e) => e.name === after)
    entries.splice(at < 0 ? entries.length : at + 1, 0, entry)
  }
  return entries
}


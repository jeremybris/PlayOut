/**
 * Set names listed as `<tag>name</tag>` in one of ES-DE's MAME XML lists. The files are bare element sequences
 * with a leading comment and no root element, so they are read with a regex rather than an XML parser.
 */
export function parseMameList(xml, tag) {
  const names = new Set()
  for (const match of String(xml).matchAll(new RegExp(`<${tag}>\\s*([^<]+?)\\s*</${tag}>`, 'g')))
    names.add(match[1].toLowerCase())
  return [...names].sort()
}

/** Build the mame-assets.json payload: lower-cased, de-duplicated, sorted BIOS and device set names. */
export function buildMameAssets(biosXml, deviceXml) {
  const bioses = parseMameList(biosXml, 'bios')
  const devices = parseMameList(deviceXml, 'device')
  if (!bioses.length) throw new Error('mamebioses.xml lists no <bios> entries')
  if (!devices.length) throw new Error('mamedevices.xml lists no <device> entries')
  return { _license: MAME_ASSETS_LICENSE, bioses, devices }
}

export async function generate() {
  const [esdeSystems, esdeFindRules, mameBioses, mameDevices] = await Promise.all([
    readJsonFile(INPUTS.systems),
    readJsonFile(INPUTS.findRules),
    readFile(INPUTS.mameBioses, 'utf8'),
    readFile(INPUTS.mameDevices, 'utf8')
  ])
  let sorting = null
  try {
    sorting = await readJsonFile(INPUTS.sorting)
  } catch {
    console.warn(
      `Sorting data not found at ${INPUTS.sorting}; manufacturer/year limited to the built-in table`
    )
  }
  return {
    systems: buildSystems(withPlayOutSystems(esdeSystems), sorting),
    findRules: buildFindRules(esdeFindRules),
    mameAssets: buildMameAssets(mameBioses, mameDevices)
  }
}

function serialize(data) {
  return JSON.stringify(data, null, 2) + '\n'
}

async function main() {
  const check = process.argv.includes('--check')
  const { systems, findRules, mameAssets } = await generate()
  const outputs = [
    [OUTPUTS.systems, serialize(systems)],
    [OUTPUTS.findRules, serialize(findRules)],
    [OUTPUTS.mameAssets, serialize(mameAssets)]
  ]
  let stale = 0
  for (const [file, text] of outputs) {
    if (check) {
      const current = await readFile(file, 'utf8').catch(() => null)
      if (current !== text) {
        stale++
        console.error(`stale: ${file}`)
      }
      continue
    }
    await mkdir(dirname(file), { recursive: true })
    await writeFile(file, text, 'utf8')
    console.log(`wrote ${file} (${text.length} bytes)`)
  }
  console.log(
    `${systems.systems.length} systems, ${systems.systems.reduce((n, s) => n + s.emulators.length, 0)} commands, ` +
      `${findRules.emulators.length} emulator rules, ${findRules.cores.length} core rules, ` +
      `${mameAssets.bioses.length} MAME BIOS sets, ${mameAssets.devices.length} MAME device sets`
  )
  if (stale) process.exit(1)
}


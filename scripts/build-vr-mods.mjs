#!/usr/bin/env node
// Generates resources/vr/vr-mods.json, the VR mod catalog of Settings › VR, from the Flat2VR release list gist
// (elliotttate's "VR mod releases" page: a `const releases = [...]` JSON array inside its index.html). The array is
// cut out of the page and read with JSON.parse (never evaluated), then cleaned: one stable id per entry, the
// "Project / download" link kept as `page`, and a GitHub link parsed into owner / repo / tag so PlayOut can read
// the project's releases. Run with `node scripts/build-vr-mods.mjs` (fetches the gist), or
// `node scripts/build-vr-mods.mjs <index.html | releases.json>` to read a saved copy; `--check` only verifies that the
// committed file is up to date. Re-runnable: the output is deterministic for the same input.
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')

/** The gist's newest revision (raw index.html). */
export const SOURCE_URL =
  'https://gist.githubusercontent.com/elliotttate/62874c06da42b6942587038711742bb2/raw/index.html'
/** The page people open (the gist rendered by htmlpreview). */
export const PAGE_URL =
  'https://htmlpreview.github.io/?https://gist.githubusercontent.com/elliotttate/62874c06da42b6942587038711742bb2/raw/index.html'

export const OUTPUT = join(ROOT, 'resources', 'vr', 'vr-mods.json')

export const NOTE =
  'VR mods listed by the Flat2VR release list (gist elliotttate/62874c06da42b6942587038711742bb2). ' +
  'Generated by scripts/build-vr-mods.mjs - edit the generator, not this file.'

const KINDS = new Set(['debut', 'alpha', 'tool', 'profile'])

export function slug(text) {
  return String(text)
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

/**
 * The JSON array literal that follows `const releases =` in the page, cut out by matching brackets (strings are
 * skipped, so a ']' inside a summary does not end it) and parsed with JSON.parse.
 */
export function extractReleases(html) {
  const text = String(html)
  const at = text.search(/\bconst\s+releases\s*=\s*\[/)
  if (at < 0) throw new Error('the page has no `const releases = [...]` list')
  const start = text.indexOf('[', at)
  let depth = 0
  let inString = false
  let end = -1
  for (let i = start; i < text.length; i++) {
    const c = text[i]
    if (inString) {
      if (c === '\\') i++
      else if (c === '"') inString = false
      continue
    }
    if (c === '"') inString = true
    else if (c === '[' || c === '{') depth++
    else if (c === ']' || c === '}') {
      depth--
      if (depth === 0) {
        end = i + 1
        break
      }
    }
  }
  if (end < 0) throw new Error('the releases list never ends')
  let data
  try {
    data = JSON.parse(text.slice(start, end))
  } catch (err) {
    throw new Error(`the releases list is not JSON: ${err.message}`, { cause: err })
  }
  if (!Array.isArray(data)) throw new Error('the releases list is not an array')
  return data
}

const NAME = /^[A-Za-z0-9._-]+$/

/**
 * owner / repo / tag of a GitHub link: a repository (https://github.com/o/r, www.github.com too), its releases page
 * (/releases, /releases/latest: no tag), one release (/releases/tag/<tag>) or one of its files
 * (/releases/download/<tag>/<file>). A link to a user's profile (one path part) is no repository: null.
 */
export function parseGithub(url) {
  let u
  try {
    u = new URL(String(url))
  } catch {
    return null
  }
  const host = u.hostname.toLowerCase()
  if (u.protocol !== 'https:' && u.protocol !== 'http:') return null
  if (host !== 'github.com' && host !== 'www.github.com') return null
  // A malformed escape (a stray '%') keeps that part as written instead of failing the whole build.
  const decode = (p) => {
    try {
      return decodeURIComponent(p)
    } catch {
      return p
    }
  }
  const parts = u.pathname.split('/').filter(Boolean).map(decode)
  if (parts.length < 2) return null
  const owner = parts[0]
  const repo = parts[1].replace(/\.git$/i, '')
  if (!NAME.test(owner) || !NAME.test(repo) || repo === '.' || repo === '..') return null
  let tag = null
  if (parts[2] === 'releases' && (parts[3] === 'tag' || parts[3] === 'download') && parts[4])
    tag = parts[4]
  return { owner, repo, tag }
}

const str = (v) => (typeof v === 'string' ? v.trim() : '')
const httpsUrl = (v) => {
  const s = str(v)
  if (!s) return null
  try {
    const u = new URL(s)
    return u.protocol === 'https:' || u.protocol === 'http:' ? u.href : null
  } catch {
    return null
  }
}
const strings = (v) => (Array.isArray(v) ? [...new Set(v.map(str).filter(Boolean))] : [])

/** One release of the page as a catalog entry (id assigned later). */
export function cleanEntry(r) {
  const title = str(r.title)
  if (!title) throw new Error('an entry without a title')
  const date = /^\d{4}-\d{2}-\d{2}$/.test(str(r.date)) ? str(r.date) : null
  const kind = KINDS.has(r.group) ? r.group : 'debut'
  const page = httpsUrl(r.source)
  const accent = /^#[0-9a-f]{6}$/i.test(str(r.accent)) ? str(r.accent).toLowerCase() : null
  return {
    title,
    author: str(r.author),
    date,
    status: str(r.status),
    kind,
    tags: strings(r.tags),
    summary: str(r.summary),
    highlights: strings(r.highlights),
    page,
    github: page ? parseGithub(page) : null,
    thread: httpsUrl(r.evidence),
    video: httpsUrl(r.video),
    reddit: httpsUrl(r.reddit),
    outside: r.outside === true,
    accent
  }
}

/**
 * The catalog: entries newest first (the page's order within a day), each with an id from its title. Ids are handed
 * out oldest first, so a later entry of the same name (a new build of a mod) gets "<slug>-<date>" and the older
 * one keeps its id (downloaded mods are remembered by id).
 */
export function buildCatalog(releases) {
  const cleaned = releases.map((r, index) => ({ ...cleanEntry(r), index }))
  const byAge = [...cleaned].sort(
    (a, b) => (a.date ?? '').localeCompare(b.date ?? '') || b.index - a.index
  )
  const taken = new Set()
  for (const e of byAge) {
    const base = slug(e.title) || 'mod'
    let id = base
    if (taken.has(id) && e.date) id = `${base}-${e.date}`
    for (let n = 2; taken.has(id); n++) id = `${base}-${e.date ?? 'x'}-${n}`
    taken.add(id)
    e.id = id
  }
  const mods = [...cleaned]
    .sort((a, b) => (b.date ?? '').localeCompare(a.date ?? '') || a.index - b.index)
    .map(({ id, ...rest }) => {
      delete rest.index
      return { id, ...rest }
    })
  const dates = mods.map((m) => m.date).filter(Boolean)
  return {
    _note: NOTE,
    source: PAGE_URL,
    updated: dates.length ? dates.reduce((a, b) => (a > b ? a : b)) : null,
    mods
  }
}

/** Reads the releases from a saved page (.html) or a saved list (.json), else fetches the gist. */
export async function readReleases(file) {
  if (file) {
    const text = await readFile(file, 'utf8')
    return /^\s*\[/.test(text) ? JSON.parse(text) : extractReleases(text)
  }
  const res = await fetch(SOURCE_URL, { headers: { 'User-Agent': 'PlayOut build script' } })
  if (!res.ok) throw new Error(`${SOURCE_URL}: HTTP ${res.status}`)
  return extractReleases(await res.text())
}

/** VR mods added by hand (not on the page), in the page's own entry shape: scripts/vr-mods-extra.json. */
export const EXTRAS = join(ROOT, 'scripts', 'vr-mods-extra.json')

export async function readExtras(file = EXTRAS) {
  const text = await readFile(file, 'utf8').catch(() => null)
  if (text === null) return []
  const list = JSON.parse(text)
  if (!Array.isArray(list)) throw new Error(`${file}: not a list`)
  return list
}

/**
 * The page's releases plus the hand-added ones. A hand-added mod whose project link the page already lists is
 * left out, so the page's own entry (with its thread and video) wins once it appears there.
 */
export function withExtras(releases, extras) {
  const key = (url) => {
    const gh = typeof url === 'string' ? parseGithub(url) : null
    return gh ? `${gh.owner}/${gh.repo}`.toLowerCase() : String(url ?? '').toLowerCase()
  }
  const listed = new Set(releases.map((r) => key(r.source)))
  return [...releases, ...extras.filter((e) => !listed.has(key(e.source)))]
}

/** The file's text, formatted the way the repository's Prettier formats JSON (so `prettier --write .` keeps it). */
export async function serialize(data) {
  const text = JSON.stringify(data, null, 2) + '\n'
  const prettier = await import('prettier').catch(() => null)
  if (!prettier) return text
  const options = (await prettier.resolveConfig(OUTPUT)) ?? {}
  return prettier.format(text, { ...options, filepath: OUTPUT })
}

async function main() {
  const args = process.argv.slice(2)
  const check = args.includes('--check')
  const file = args.find((a) => !a.startsWith('--'))
  const catalog = buildCatalog(withExtras(await readReleases(file), await readExtras()))
  const text = await serialize(catalog)
  const github = catalog.mods.filter((m) => m.github).length
  console.log(
    `${catalog.mods.length} VR mods (${github} on GitHub, ${catalog.mods.length - github} elsewhere), newest ${catalog.updated}`
  )
  if (check) {
    const current = await readFile(OUTPUT, 'utf8').catch(() => null)
    if (current !== text) {
      console.error(`stale: ${OUTPUT}`)
      process.exit(1)
    }
    return
  }
  await mkdir(dirname(OUTPUT), { recursive: true })
  await writeFile(OUTPUT, text, 'utf8')
  console.log(`wrote ${OUTPUT} (${text.length} bytes)`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch((err) => {
    console.error(err)
    process.exit(1)
  })
}

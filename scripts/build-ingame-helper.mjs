// Builds PlayOut's in-game overlay (ingame-helper/, C++ with MSVC) into resources/ingame, which electron-builder ships
// unpacked:
//   PlayOutIngame64.exe   probe / inject / watch a game process (runs beside PlayOut, never inside the game)
//   PlayOutOverlay64.dll  the hook DLL that `inject` loads into an x64 Direct3D 11 game
//   LICENSES.txt          PlayOut's own licence (the helper and the DLL contain no third-party code)
//   playout-ingame-version.txt  helper version and build time
// It first regenerates ingame-helper/common/anticheat_names.h from anticheat_names.json. Needs Visual Studio 2022
// (Build Tools are enough: MSVC v143, a Windows 10/11 SDK), CMake and Ninja. VCVARS64=<path to vcvars64.bat> overrides
// where vcvars64.bat is looked for. Run it after changing the helper (`node scripts/build-ingame-helper.mjs`); the
// output is kept in the repository, so `npm run build` needs no C++ toolchain.
import { execFileSync } from 'node:child_process'
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const project = join(root, 'ingame-helper')
const buildDir = join(project, 'build')
const target = join(root, 'resources', 'ingame')

/** The files the build ships. */
const SHIPPED = ['PlayOutIngame64.exe', 'PlayOutOverlay64.dll']

const VCVARS_CANDIDATES = [
  process.env.VCVARS64,
  ...['BuildTools', 'Community', 'Professional', 'Enterprise'].flatMap((edition) => [
    join(
      'C:/Program Files (x86)/Microsoft Visual Studio/2022',
      edition,
      'VC/Auxiliary/Build/vcvars64.bat'
    ),
    join(
      'C:/Program Files/Microsoft Visual Studio/2022',
      edition,
      'VC/Auxiliary/Build/vcvars64.bat'
    )
  ])
].filter(Boolean)

/** anticheat_names.h's text for the lists in anticheat_names.json. */
export function antiCheatHeader(lists) {
  const array = (name, items) => {
    for (const item of items) {
      if (!/^[a-z0-9 ._-]+\*?$/.test(item))
        throw new Error(`anticheat_names.json: bad name ${item}`)
    }
    return `inline constexpr const wchar_t* ${name}[] = {\n${items.map((i) => `    L"${i}",`).join('\n')}\n};\n`
  }
  return `// Generated by scripts/build-ingame-helper.mjs from anticheat_names.json; edit the JSON, not this file.
// Lower-case base names, matched case-insensitively; a name ending in * matches every base name starting with the rest.
#pragma once

namespace playout::anticheat {

// Kernel drivers: any of these loaded on the system means never inject.
${array('kDrivers', lists.drivers)}
// Modules (DLLs, or the game's own exe) loaded in the target process.
${array('kModules', lists.modules)}
// Anti-cheat services and programs running on the system.
${array('kProcesses', lists.processes)}
}  // namespace playout::anticheat
`
}

function findVcvars() {
  const found = VCVARS_CANDIDATES.find((p) => existsSync(p))
  if (!found) throw new Error('vcvars64.bat not found: install VS 2022 Build Tools or set VCVARS64')
  return found
}

/** Runs cmake inside the vcvars64 environment through a small .cmd file. */
function cmake(vcvars, args) {
  mkdirSync(buildDir, { recursive: true })
  const script = join(buildDir, 'run-cmake.cmd')
  const quoted = args.map((a) => `"${a}"`).join(' ')
  writeFileSync(
    script,
    // vcvars64 looks for vswhere.exe on PATH; it lives in the Visual Studio Installer folder.
    '@echo off\r\n' +
      'set "PATH=%PATH%;%ProgramFiles(x86)%\\Microsoft Visual Studio\\Installer"\r\n' +
      `call "${vcvars}" >nul || exit /b 1\r\ncmake ${quoted} || exit /b 1\r\n`
  )
  execFileSync('cmd.exe', ['/d', '/c', script], { cwd: project, stdio: 'inherit' })
}

function main() {
  const lists = JSON.parse(readFileSync(join(project, 'common', 'anticheat_names.json'), 'utf8'))
  writeFileSync(join(project, 'common', 'anticheat_names.h'), antiCheatHeader(lists))

  const vcvars = findVcvars()
  cmake(vcvars, ['-S', project, '-B', buildDir, '-G', 'Ninja', '-DCMAKE_BUILD_TYPE=Release'])
  cmake(vcvars, ['--build', buildDir, '--config', 'Release'])
  for (const name of SHIPPED) {
    if (!existsSync(join(buildDir, name))) throw new Error(`the build produced no ${name}`)
  }

  const version = /project\(PlayOutIngame VERSION ([0-9.]+)/.exec(
    readFileSync(join(project, 'CMakeLists.txt'), 'utf8')
  )[1]
  const licence = readFileSync(join(root, 'LICENSE'), 'utf8')
  const licences = `PlayOut in-game overlay (PlayOutIngame64.exe, PlayOutOverlay64.dll) ${version}
Part of PlayOut. Both files are PlayOut's own code; they contain no third-party code (the hooks are plain vtable and
import-table patches, no detour library).

${'='.repeat(100)}
PlayOut - LICENSE
${'='.repeat(100)}

${licence.trim()}
`

  rmSync(target, { recursive: true, force: true })
  mkdirSync(target, { recursive: true })
  for (const name of SHIPPED) copyFileSync(join(buildDir, name), join(target, name))
  writeFileSync(join(target, 'LICENSES.txt'), licences.replace(/\r\n/g, '\n'))
  writeFileSync(
    join(target, 'playout-ingame-version.txt'),
    `${version} ${new Date().toISOString()}\n`
  )
  console.log(`build-ingame-helper: ${target} (PlayOut in-game overlay ${version})`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
